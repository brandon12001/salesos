const assert=require('node:assert/strict');
const cp=require('node:child_process'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const core=require('./core.cjs');
global.window={SalesCore:core};
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'salesos-briefing-'));
const result=cp.spawnSync(process.execPath,['node_modules/typescript/bin/tsc','--target','es2022','--module','commonjs','--strict','--skipLibCheck','--outDir',dir,'--rootDir','src','src/lib/companyBriefing.ts','src/lib/companyEnrichment.ts'],{encoding:'utf8'});
if(result.status!==0)throw Error(result.stdout||result.stderr);
const {briefingStamp,saveManualCompanyBriefing}=require(path.join(dir,'lib/companyBriefing.js'));
const {planCompanyEnrichment,applyCompanyEnrichment}=require(path.join(dir,'lib/companyEnrichment.js'));
const s=core.newState();
const lead=core.createLead(s,{company:'Fictional Clearview Recruitment Ltd',sector:'Recruitment',companyNumber:'00076543',contact:'Alex Sample',email:'alex@example.invalid',businessDescription:'Recruitment firm — recruits professionals for employers.',researchRationale:'Original detailed evidence with research scores',readiness:1});
core.addTask(s,lead,'call','Cold call',core.today(),{});
const before=JSON.stringify({contacts:lead.contacts,tasks:s.tasks,activities:s.activities,researchRationale:lead.researchRationale,stage:lead.stage,readiness:lead.readiness});
assert.equal(lead.companyBriefing,'','New prospects start without invented research');
let stamp=briefingStamp(lead);
const draft='The company focuses on recruitment for specialist employers. Its website describes a dedicated executive-search service, and it serves clients across several sectors.';
saveManualCompanyBriefing(s,lead.id,draft,stamp);
assert.equal(lead.companyBriefing,draft);
assert.ok(lead.companyBriefingEditedAt);
assert.throws(()=>saveManualCompanyBriefing(s,lead.id,'Stale change from another device.',stamp),/changed elsewhere/);
const restored=core.normalize(JSON.parse(JSON.stringify(s)));
assert.equal(restored.leads.find(l=>l.id===lead.id).companyBriefing,draft,'JSON backup and cloud normalisation preserve briefing');
assert.equal(JSON.stringify({contacts:lead.contacts,tasks:s.tasks,activities:s.activities,researchRationale:lead.researchRationale,stage:lead.stage,readiness:lead.readiness}),before,'Manual briefing cannot change sales state');
const csv='Company Name,Company Number,Business Description,Standardised Industry,Company Briefing\nFictional Clearview Recruitment Ltd,00076543,Recruitment firm - specialist hiring,Recruitment & Staffing,A replacement briefing that would overwrite seller notes.';
const plan=planCompanyEnrichment(s,csv,{replaceResearchCopy:false});
assert.equal(plan.matched,1);
applyCompanyEnrichment(s,plan);
assert.equal(lead.companyBriefing,draft,'Re-import preserves seller-authored background');
assert.throws(()=>saveManualCompanyBriefing(s,lead.id,'short',briefingStamp(lead)),/at least 35/);
assert.throws(()=>saveManualCompanyBriefing(s,lead.id,'x'.repeat(1401),briefingStamp(lead)),/1,400/);
saveManualCompanyBriefing(s,lead.id,'',briefingStamp(lead));
assert.equal(lead.companyBriefing,'','Manually clearing an outdated paragraph is supported');
const other=core.createLead(s,{company:'Fictional Import Example Ltd',companyNumber:'00076544',sector:'Manufacturing'});
const csv2='Company Name,Company Number,Business Description,Standardised Industry,Company Briefing\nFictional Import Example Ltd,00076544,Manufacturer - industrial machinery,Manufacturing,Builds custom industrial machinery and supplies a range of customers across Europe.';
const plan2=planCompanyEnrichment(s,csv2);
assert.equal(plan2.changed,1);
applyCompanyEnrichment(s,plan2);
assert.match(other.companyBriefing,/Builds custom industrial machinery/);
assert.equal(core.normalize(JSON.parse(JSON.stringify(s))).leads.find(l=>l.id===other.id).companyBriefing,other.companyBriefing);
console.log('PASS: editable disclosure, stale writes, backup persistence, non-destructive imports and independent call/research state');
