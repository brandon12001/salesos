const assert=require('node:assert/strict'),cp=require('node:child_process'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const core=require('./core.cjs');global.window={SalesCore:core};
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'salesos-lead-factory-'));
const r=cp.spawnSync(process.execPath,['node_modules/typescript/bin/tsc','--target','es2022','--module','commonjs','--strict','--skipLibCheck','--outDir',dir,'--rootDir','src','src/lib/leadFactory.ts'],{encoding:'utf8'});
if(r.status!==0)throw Error(r.stdout||r.stderr);
const f=require(path.join(dir,'lib/leadFactory.js'));
const date=core.today(),ch='https://find-and-update.company-information.service.gov.uk/company/';
const sample=(name,number,sector='recruitment',priority=55)=>({company:name,companyNumber:number,sector,sicCodes:sector==='recruitment'?['78200']:['46690'],incorporated:'2017-01-01',sourceUrl:ch+number,priority,reason:'Registry shows active company under relevant SIC. FX unverified.',foundAt:date+'T12:00:00Z'});
const s=core.newState();
const a=sample('Fictional Staffing Operations Ltd','12000001');
const b=sample('Fictional Engineering Distributors Ltd','12000002','goods',61);
const existing=core.createLead(s,{company:'Existing Goods Ltd',companyNumber:'12000003',leadPool:'reserve'});
try{
 const first=f.addDiscoveries(s,[a,b,sample('Existing Goods Ltd','12000003')],'recruitment',1);
 assert.deepEqual(first,{added:2,existing:1});
 assert.equal(f.leadFactory(s).candidates.length,2);
 assert.equal(s.leads.length,1,'research must not insert companies into live reserve');
 assert.equal(s.tasks.length,0,'research does not create outreach work');
 assert.equal(f.addDiscoveries(s,[a,b],'recruitment',2).added,0,'reruns never duplicate the staging queue');
 assert.equal(f.leadFactory(s).cursors.recruitment,2);
 assert.throws(()=>f.moveCleared(s,['ch:12000001']),/not cleared/);
 assert.throws(()=>f.markOwned(s,'ch:12000001',''),/owner/);
 f.markAvailable(s,'ch:12000001');
 assert.equal(f.leadFactory(s).candidates[0].status,'cleared');
 assert.throws(()=>f.markAvailable(s,'ch:12000001'),/unchecked/,'check cannot be repeated casually');
 assert.equal(f.moveCleared(s,['ch:12000001']),1);
 const added=s.leads.find(l=>l.companyNumber==='12000001');
 assert.ok(added);assert.equal(added.leadPool,'reserve');assert.equal(added.crmClearance,'cleared');
 assert.equal(added.contacts.length,0,'no contacts invented by discovery');
 assert.equal(added.researchConfidence,'Low — Companies House registry screening only');
 assert.equal(added.opportunityScore,55);assert.equal(added.readiness,1);
 assert.equal(s.tasks.length,0,'moving to reserve still creates no outreach');
 assert.throws(()=>f.moveCleared(s,['ch:12000001']),/not cleared/,'cannot repeat transfer');
 assert.throws(()=>f.markOwned(s,'ch:12000002','Sarah','2099-01-01'),/past date/);
 const held=f.markOwned(s,'ch:12000002','Sarah');
 assert.equal(held.crmClearance,'hold');assert.equal(held.leadPool,'reserve');assert.equal(held.crmLastActivityAt,'');
 assert.match(held.crmNote,/Owner: Sarah/);
 assert.ok(core.dupeQueue(s).some(l=>l.id===held.id),'owned company appears in existing duplicate queue');
 assert.equal(core.dupeState(held),'missing-activity','missing manager-only date does not infer eligibility');
 assert.equal(s.tasks.length,0,'held company never generates a call task');
 assert.equal(f.leadFactory(s).candidates.find(c=>c.id==='ch:12000002').status,'held');
 const n=f.addDiscoveries(s,[a,b],'goods',3);
 assert.equal(n.added,0);assert.equal(n.existing,2);
 assert.throws(()=>f.addDiscoveries(s,[sample('Implausibly Sure Ltd','12000004','recruitment',96)],'recruitment',4),/priority/,'registry-only discoveries cannot impersonate confirmed FX');
 assert.throws(()=>f.markAvailable(s,'ch:12000002'),/unchecked/);
 const c=sample('Fictional New Staffing Ltd','12000004');
 f.addDiscoveries(s,[c],'recruitment',5);f.dismissCandidate(s,'ch:12000004');
 assert.equal(f.leadFactory(s).candidates.find(x=>x.companyNumber==='12000004').status,'dismissed');
 const normal=core.normalize(JSON.parse(JSON.stringify(s)));
 assert.equal(f.leadFactory(normal).candidates.length,3,'research queue survives cloud/JSON normalisation');
 assert.equal(normal.leads.length,3,'original lead and two authorised reserve transfers only');
 assert.equal(existing.crmClearance,'unknown','untouched original record');
 console.log('PASS: automated discovery staging, identity dedupe, manual clearance, bulk-ready transfer, holds routed to existing dupe queue, no invented activity, persisted metadata.');
}catch(error){console.error(error);process.exitCode=1}
