const assert=require('node:assert/strict'),cp=require('node:child_process'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'salesos-registry-quality-'));
const p=cp.spawnSync(process.execPath,['node_modules/typescript/bin/tsc','--target','es2022','--module','commonjs','--strict','--skipLibCheck','--outDir',dir,'--rootDir','.','api/registry-quality.ts'],{encoding:'utf8'});
if(p.status)throw Error(p.stdout||p.stderr);
const {assessRegistry,registryBase,screenedPriority}=require(path.join(dir,'api/registry-quality.js'));
const name='Fictional International Contractors Ltd',num='12000123';
const base={company_name:name,company_number:num,company_status:'active',accounts:{last_accounts:{type:'small'},next_accounts:{overdue:false}},confirmation_statement:{overdue:false}};
const now='2026-11-24T09:00:00Z';
const ok=assessRegistry(name,num,base,now);
assert.equal(ok.risk,'ok');assert.equal(ok.flags.length,0);
assert.ok(registryBase('recruitment','78200','2014-01-01')<35,'registry alone never high quality');
assert.ok(screenedPriority('recruitment','78200','2014-01-01',ok)<35);
const strike=assessRegistry(name,num,{...base,company_status_detail:'active-proposal-to-strike-off'},now);
assert.equal(strike.risk,'excluded');assert.match(strike.flags.join(' '),/strike off/i);
assert.equal(screenedPriority('recruitment','78200','2014-01-01',strike),0);
const dissolved=assessRegistry(name,num,{...base,company_status:'dissolved'},now);
assert.equal(dissolved.risk,'excluded');
const dormant=assessRegistry(name,num,{...base,accounts:{last_accounts:{type:'dormant'},next_accounts:{overdue:false}}},now);
assert.equal(dormant.risk,'excluded');
const overdue=assessRegistry(name,num,{...base,accounts:{...base.accounts,next_accounts:{overdue:true}},confirmation_statement:{overdue:true}},now);
assert.equal(overdue.risk,'review');assert.match(overdue.flags.join(' '),/accounts overdue/i);
const holding=assessRegistry('Fictional Group Holdings Ltd',num,{...base,company_name:'Fictional Group Holdings Ltd'},now);
assert.equal(holding.risk,'review');assert.match(holding.flags.join(' '),/holding/i);
const missing=assessRegistry(name,num,null,now);assert.equal(missing.risk,'unverified');
const mismatched=assessRegistry(name,num,{...base,company_number:'99999999'},now);
assert.equal(mismatched.risk,'unverified','wrong legal record is not evidence');
const renamed=assessRegistry(name,num,{...base,company_name:'Fictional Different Group Ltd'},now);
assert.equal(renamed.risk,'review');
assert.equal(assessRegistry(name,num,{...base,has_insolvency_history:true},now).risk,'review');
console.log('PASS: official profile checks quarantine strike-off, dormant, overdue, holding, dissolved, mismatched and unverified companies; registry scores stay low.');
